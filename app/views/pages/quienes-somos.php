        <h2>Asociación Mexicana de Unidades de Verificación de Instalaciones Eléctricas</h2>
        <p>
            La AMUVIE, A.C., nace el 27 de Junio de 2014, gracias a un grupo de Unidades de Verificaciones de
            Instalaciones eléctricas, con experiencia profesional en esta actividad desde los veinte años hasta
            de reciente creación; quienes se encuentran ubicados en los diferentes Estados que conforman nuestra
            República Mexicana.
        </p>
        <p>
            Todos tienen los contactos con la SENER, CONUEE, EMA, C.F.E., con la finalidad de mantenerse
            actualizados en el dinámico mundo de la ingeniería específicamente en el campo de las instalaciones
            eléctricas, para la utilización. Desde su inicio se han llevado a cabo eventos en diferentes estados
            de la República, para que todos y cada uno de los Socios participen de forma activa a favor de los
            UVIES de cada región.
        </p>
        <p>
            De igual forma, se creó la página WEB www.amuvie.mx en la que se está informando todos y cada uno de
            los eventos realizados, así como ligas de interés para el asociado y público en general.
        </p>

